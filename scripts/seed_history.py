"""Import months of Golden Gate Freight history so the dashboard opens on a company that has been operating.

Seed only: resolved cases, carrier invoices, posted journals, case files (source records) and the counterparties
they name are written directly through the admin-only `import_history_batch` reducer, with no model calls, no
agents and no task, dispatch or review rows. Everything is generated by sim/history.py from data/world.json and
is deterministic for a given world, seed, end date, day count and load count, so a rerun replays the same write
ids and changes nothing. Imported rows are marked (HIST- ids, `"imported": true` case files) and stay visible
after "Start fresh", which only hides earlier live activity.

    python -m scripts.seed_history --dry-run                                  # plan and totals, no writes
    python -m scripts.seed_history --server http://127.0.0.1:3010 --database hist-scratch --docs
    python -m scripts.seed_history --server https://maincloud.spacetimedb.com --database at350-freightops
    python -m scripts.seed_history --server ... --database ... --undo         # take it all back out

Local servers use the admin identity scripts.spacetime_admin created when it published (data/w2/<db>/).
Maincloud uses the logged-in publisher through `spacetime call`, like scripts.spacetime_cloud, and only for
at350-freightops. `--docs` renders the PDFs and JSON for each load into <data-dir>/docs on this machine; the
dashboard's evidence viewer reads that folder on the machine that serves the dashboard.
"""
from __future__ import annotations

import argparse
import json
import os
import pathlib
import subprocess
import sys
import time
import uuid
from collections.abc import Callable
from datetime import UTC, date, datetime
from urllib.parse import quote, urlparse

import httpx

from common.spacetime_client import canonical_sql_column
from integrations import directory
from sim import docs, history

LOCAL_HOSTS = {"localhost", "127.0.0.1", "::1"}
IMPORT_REDUCER = "import_history_batch"
REMOVE_REDUCER = "remove_imported_history"
# `spacetime call` passes the payload as one argument, JSON-escaped a second time (about 1.2x): Linux caps a
# single argument at 128 KiB, so cloud batches stay at or under CLOUD_MAX_BATCH_BYTES of payload.
CLOUD_BATCH_BYTES = 50_000
CLOUD_MAX_BATCH_BYTES = 90_000
LOCAL_BATCH_BYTES = 200_000
REMOVE_LIMIT = 40


def _rows(payload: object) -> list[dict]:
    result = payload[0]  # type: ignore[index]
    names = [canonical_sql_column(e["name"].get("some") if isinstance(e["name"], dict) else e["name"])
             for e in result["schema"]["elements"]]
    return [dict(zip(names, row, strict=True)) for row in result["rows"]]


class LocalTarget:
    """A loopback server, through the admin identity scripts.spacetime_admin stored when it published."""

    def __init__(self, server: str, database: str):
        from scripts.spacetime_admin import LocalAdmin
        self.admin = LocalAdmin(server, database)
        if "admin" not in self.admin.identities:
            raise SystemExit(f"No local admin identity for {database}; publish it first: "
                             f"python -m scripts.spacetime_admin --server {server} --database {database} publish")
        self.label = f"{server}/{database}"
        self.batch_bytes = LOCAL_BATCH_BYTES

    def call(self, reducer: str, payload: dict) -> None:
        try:
            self.admin.raw_call("admin", reducer, payload)
        except RuntimeError as error:
            # 530 is a reducer that threw; anything else (502, 503) may be transient and is retried.
            if "(530)" in str(error):
                from scripts.spacetime_cloud import refusal_reason
                raise Refused(refusal_reason(str(error))) from error
            raise

    def query(self, sql: str) -> list[dict]:
        token = self.admin.identity("admin")["token"]
        response = self.admin.client.post(f"/v1/database/{quote(self.admin.database, safe='')}/sql", content=sql,
                                          headers={"Authorization": f"Bearer {token}"})
        response.raise_for_status()
        return _rows(response.json())

    def close(self) -> None:
        self.admin.client.close()


class CloudTarget:
    """Maincloud at350-freightops only, as the verified publisher (scripts.spacetime_cloud.CloudAdmin)."""

    def __init__(self, server: str, database: str):
        from scripts.spacetime_cloud import CloudAdmin
        self.admin = CloudAdmin(server, database)
        self.label = f"{server}/{database}"
        self.batch_bytes = CLOUD_BATCH_BYTES

    def call(self, reducer: str, payload: dict) -> None:
        from scripts.spacetime_cloud import CloudReducerRefused
        try:
            self.admin.call("admin", reducer, payload)
        except CloudReducerRefused as error:
            raise Refused(str(error)) from error

    def query(self, sql: str) -> list[dict]:
        self.admin.verify_target()
        response = self.admin.client.post(f"/v1/database/{self.admin.database}/sql", content=sql)
        response.raise_for_status()
        return _rows(response.json())

    def close(self) -> None:
        self.admin.client.close()


class Refused(RuntimeError):
    """The reducer refused the batch (SpacetimeDB answers 530); retrying the same payload cannot help."""


def connect(server: str, database: str):
    if urlparse(server).hostname in LOCAL_HOSTS:
        return LocalTarget(server, database)
    return CloudTarget(server, database)


def call(target, reducer: str, payload: dict, *, attempts: int = 4, sleep: Callable[[float], None] = time.sleep) -> None:
    """Send one batch, resending the identical payload (same write id) after a transport failure: an exact
    replay is a no-op in the module, so a batch that did commit before the failure is never applied twice."""
    for attempt in range(1, attempts + 1):
        try:
            target.call(reducer, payload)
            return
        except Refused:
            raise
        except (httpx.HTTPError, RuntimeError, subprocess.TimeoutExpired) as error:
            if attempt == attempts:
                raise
            print(f"  {reducer} attempt {attempt} failed ({error.__class__.__name__}); retrying the same payload",
                  file=sys.stderr)
            sleep(2 ** (attempt - 1))


def imported_cases(target) -> list[dict]:
    return [row for row in target.query('SELECT * FROM "case"') if str(row["case_id"]).startswith(history.PREFIX)]


def manifest(target) -> dict | None:
    rows = target.query(f"SELECT * FROM \"source_record\" WHERE \"id\" = '{history.MANIFEST_ID}'")
    return rows[0] if rows else None


def _lines(raw) -> list[dict]:
    """Journal lines come back from SQL as positional tuples."""
    return [line if isinstance(line, dict) else {"account": line[0], "debit": line[1], "credit": line[2]}
            for line in raw]


def dashboard_totals(target, now: datetime) -> dict:
    """What Finance shows: imported history plus every live posting (since the Start fresh epoch, if one is set)."""
    since = None
    try:
        epoch = target.query('SELECT * FROM "view_epoch"')
        since = epoch[0]["since"] if epoch else None
    except httpx.HTTPError:
        pass
    entries = [{"id": row["id"], "posted_at": row["posted_at"], "lines": _lines(row["lines"])}
               for row in target.query('SELECT * FROM "ledger_entry"')]
    visible = [e for e in entries if e["id"].startswith(history.PREFIX) or not since or e["posted_at"] >= since]
    return {**history.kpis(visible, now), "epoch": since, "ledger_entries": len(visible)}


def render_documents(plan: history.History, data_dir: pathlib.Path) -> tuple[int, int]:
    """Write each load's PDFs and JSON into <data_dir>/docs. A document is skipped only when both its files are
    there, so a render interrupted between the PDF and its JSON is redone on the next run."""
    os.environ["SIM_DATA_DIR"] = str(data_dir)
    folder = docs.docs_dir()
    written = 0
    for ref, kind, data in plan.documents:
        if not all((folder / f"{ref}{suffix}").exists() for suffix in (".pdf", ".json")):
            docs.write(ref, kind, data)
            written += 1
    files = [folder / f"{ref}{suffix}" for ref, _, _ in plan.documents for suffix in (".pdf", ".json")]
    return written, sum(path.stat().st_size for path in files if path.exists())


def remove_documents(load_ids: list[str], data_dir: pathlib.Path) -> int:
    """Delete the documents of these imported loads. Their refs follow from the load id alone
    (history.document_refs), so removal needs neither the world file nor the generator."""
    folder = data_dir / "docs"
    removed = 0
    for ref in (ref for load_id in load_ids for ref in history.document_refs(load_id)):
        for suffix in (".pdf", ".json"):
            path = folder / f"{ref}{suffix}"
            if path.exists():
                path.unlink()
                removed += 1
    return removed


def seed(target, plan: history.History, batch_bytes: int) -> int:
    stored = manifest(target)
    if stored and stored["digest"] != plan.manifest["digest"]:
        params = json.loads(stored["record_json"])
        raise SystemExit("A different history is already imported here (seed {seed}, end {end}, {days} days). "
                         "Remove it first with --undo, then seed again.".format(**params))
    if stored:
        print("This history is already imported (or partly); replaying its batches is a no-op that fills any gap.")
    else:
        # The manifest rides in the first batch, so imported cases without it predate it: only proceed when every
        # one of them belongs to this plan, or two histories would mix.
        planned = {c["case_id"] for c in plan.cases}
        stray = sorted(c["case_id"] for c in imported_cases(target) if c["case_id"] not in planned)
        if stray:
            raise SystemExit(f"{len(stray)} imported cases here (e.g. {stray[0]}) are not part of this history and no "
                             "manifest says what they are. Remove them first with --undo, then seed again.")
    payloads = history.batches(plan, batch_bytes)
    for index, payload in enumerate(payloads, 1):
        call(target, IMPORT_REDUCER, payload)
        print(f"  batch {index}/{len(payloads)}: {len(payload.get('cases', []))} cases, "
              f"{len(payload.get('ledger_entries', []))} journals")
    return len(payloads)


def undo(target, limit: int = REMOVE_LIMIT) -> int:
    calls = 0
    while True:
        remaining = len(imported_cases(target))
        call(target, REMOVE_REDUCER, {"write_id": f"history-remove:{uuid.uuid4()}", "limit": limit})
        calls += 1
        print(f"  removed up to {limit} of {remaining} imported cases")
        if remaining <= limit:
            break
    left = len(imported_cases(target))
    if left or manifest(target):
        raise SystemExit(f"Removal incomplete: {left} imported cases remain")
    return calls


def summary(plan: history.History) -> str:
    meta = json.loads(plan.manifest["record_json"])
    counts, totals = meta["counts"], meta["totals_at_end"]
    first = min(c["opened_at"] for c in plan.cases)[:10]
    return (f"{counts['cases']} resolved cases ({first} to {plan.params['end']}), {counts['invoices']} carrier invoices, "
            f"{counts['ledger_entries']} journals, {counts['companies']} counterparties, {counts['documents']} documents\n"
            f"At the end of the window: cash ${totals['cash']:,.2f} (never below ${totals['lowest_cash']:,.2f}), "
            f"AR ${totals['ar']:,.2f}, AP ${totals['ap']:,.2f}, revenue MTD ${totals['revenue_mtd']:,.2f}, "
            f"30-day margin {totals['gross_margin_pct']}%")


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--server", default=os.getenv("SPACETIME_URL", "http://127.0.0.1:3000"))
    parser.add_argument("--database", default=os.getenv("SPACETIME_DB", "freightops"))
    # Left unset, these come from the history already on the server (its manifest), else the defaults shown.
    parser.add_argument("--days", type=int, help=f"days of history (default {history.DEFAULT_DAYS})")
    parser.add_argument("--loads", type=int, help="total loads (default: 5-8 per business day)")
    parser.add_argument("--seed", type=int, help=f"generator seed (default {history.DEFAULT_SEED})")
    parser.add_argument("--end", type=date.fromisoformat, help="last day of history, YYYY-MM-DD (default yesterday UTC)")
    parser.add_argument("--source", help=f"source tag recorded on every imported row (default {history.DEFAULT_SOURCE})")
    parser.add_argument("--world", type=pathlib.Path, help="world file (default WORLD_FILE or data/world.json)")
    parser.add_argument("--data-dir", type=pathlib.Path, default=pathlib.Path(os.getenv("SIM_DATA_DIR", "data")))
    parser.add_argument("--docs", action="store_true", help="also render each load's documents into <data-dir>/docs")
    parser.add_argument("--max-batch-bytes", type=int, help="payload size per reducer call")
    parser.add_argument("--dry-run", action="store_true", help="generate and report; write nothing")
    parser.add_argument("--undo", action="store_true", help="remove every imported row (and, with --docs, its files)")
    args = parser.parse_args(argv)

    if args.world:
        os.environ["WORLD_FILE"] = str(args.world)
    world = directory.load()
    explicit = {key: getattr(args, key) for key in ("seed", "end", "days", "loads", "source")
                if getattr(args, key) is not None}

    def plan_for(params: dict) -> history.History:
        end = params.get("end") or history.default_end()
        if isinstance(end, str):
            end = date.fromisoformat(end)
        if end >= datetime.now(UTC).date():
            raise SystemExit("--end must be a day before today (UTC): imported history never reaches into the future")
        return history.generate(world, seed=params.get("seed", history.DEFAULT_SEED), end=end,
                                days=params.get("days") or history.DEFAULT_DAYS, loads=params.get("loads"),
                                source=params.get("source") or history.DEFAULT_SOURCE)

    if args.dry_run:
        plan = plan_for(explicit)
        print(summary(plan))
        payloads = history.batches(plan, args.max_batch_bytes or LOCAL_BATCH_BYTES)
        print(f"Dry run: {len(payloads)} batches, largest {max(len(json.dumps(p)) for p in payloads):,} bytes; "
              "nothing written")
        if args.docs:
            print(f"--docs would render {len(plan.documents)} documents into {args.data_dir / 'docs'}")
        return

    target = connect(args.server, args.database)
    started = time.monotonic()
    try:
        if args.undo:
            # Removal works from what is in the database: the reducer removes HIST- rows, and the documents to
            # delete follow from the imported loads' ids. Nothing is regenerated, so a changed or missing world
            # file cannot block it or point it at the wrong files.
            load_ids = sorted({str(c["load_id"]) for c in imported_cases(target) if c.get("load_id")})
            print(f"Removing imported history ({len(load_ids)} loads) from {target.label}")
            calls = undo(target)
            if args.docs:
                print(f"Removed {remove_documents(load_ids, args.data_dir)} document files")
            print(f"Done in {time.monotonic() - started:.1f}s ({calls} calls)")
            return
        # A history already here decides the parameters unless they are given: rerunning tomorrow then means
        # that history, not one generated for a new default end date.
        stored = manifest(target)
        params = explicit
        if stored and not explicit:
            params = json.loads(stored["record_json"])
            print(f"Using the imported history's parameters: seed {params['seed']}, end {params['end']}, "
                  f"{params['days']} days")
        plan = plan_for(params)
        print(summary(plan))
        if params.get("loads") is None and len(plan.cases) > 600:
            print("warning: more than 600 imported cases; the dashboard slows past ~2k cases", file=sys.stderr)
        if args.docs:
            written, size = render_documents(plan, args.data_dir)
            print(f"Documents: {written} written, {len(plan.documents)} on file, {size / 1e6:.1f} MB in "
                  f"{args.data_dir / 'docs'}")
        print(f"Importing into {target.label}")
        batch_bytes = args.max_batch_bytes or target.batch_bytes
        if isinstance(target, CloudTarget) and batch_bytes > CLOUD_MAX_BATCH_BYTES:
            raise SystemExit(f"--max-batch-bytes over {CLOUD_MAX_BATCH_BYTES:,} would exceed the CLI argument limit")
        try:
            count = seed(target, plan, batch_bytes)
        except Refused as error:
            raise SystemExit(f"The module refused a batch, so nothing in it was written: {error}") from None
        elapsed = time.monotonic() - started
        totals = dashboard_totals(target, datetime.now(UTC))
        print(f"Done in {elapsed:.1f}s ({count} calls). {len(imported_cases(target))} imported cases on the server.")
        print("Finance now: cash ${cash:,.2f}, AR ${ar:,.2f}, AP ${ap:,.2f}, revenue MTD ${revenue_mtd:,.2f}, "
              "30-day margin {gross_margin_pct}% over {ledger_entries} journals (epoch {epoch})".format(**totals))
    finally:
        target.close()


if __name__ == "__main__":
    main()
